import AppKit

/// Polls the general pasteboard and turns new copies into `ClipItem`s.
@MainActor
final class ClipboardMonitor {
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    var onItem: (ClipItem) -> Void = { _ in }

    init() { lastChangeCount = NSPasteboard.general.changeCount }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == Paster.ignoredChangeCount { return }
        let types = Set(pasteboard.types ?? [])
        if !types.isDisjoint(with: Self.ignoredTypes) { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, Settings.shared.clipboardExcludedApps.contains(id) { return }
        if let item = capture(app: app) { onItem(item) }
    }

    private func capture(app: NSRunningApplication?) -> ClipItem? {
        let bundleID = app?.bundleIdentifier
        let name = app?.localizedName

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(kind: .file, fileURLs: urls, sourceBundleID: bundleID, sourceName: name,
                            contentHash: ClipItem.hash("f:" + urls.map(\.path).joined(separator: "\n")))
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let hash = ClipItem.hash("t:" + string)
            func make(_ kind: ClipItem.Kind, rtf: Data? = nil) -> ClipItem {
                ClipItem(kind: kind, text: string, rtf: rtf, sourceBundleID: bundleID, sourceName: name, contentHash: hash)
            }
            if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
               let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https", url.host != nil {
                return make(.link)
            }
            if ClipItem.looksLikeCode(string, sourceBundleID: bundleID) { return make(.code) }
            if let rtf = pasteboard.data(forType: .rtf) { return make(.richText, rtf: rtf) }
            return make(.text)
        }

        let png = pasteboard.data(forType: .png)
        let tiff = pasteboard.data(forType: .tiff)
        guard let data = png ?? tiff.flatMap({ NSImage(data: $0)?.pngData }) else { return nil }
        let file = UUID().uuidString + ".png"
        do { try data.write(to: ClipItem.imageDirectory.appendingPathComponent(file), options: .atomic) } catch { return nil }
        return ClipItem(kind: .image, imageFile: file, sourceBundleID: bundleID, sourceName: name,
                        contentHash: ClipItem.hash(data))
    }
}
